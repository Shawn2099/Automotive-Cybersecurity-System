"""Tiny diagram toolkit: one set of primitives (inches, y up) rendered to matplotlib AND emitted as TikZ.

Keeps the PDF/PNG and the TikZ source identical in layout. Greyscale-safe fills + line styles.
"""
from __future__ import annotations

import matplotlib.pyplot as plt
from matplotlib.patches import FancyBboxPatch

from paper.experiments import style

DIAG_DIR = style.PAPER / "diagrams"
FILLS = {"w": "#FFFFFF", "g1": "#F0F0F0", "g2": "#DCDCDC", "g3": "#C4C4C4", "atk": "#F2C9B8", "hw": "#E3EEF7"}
_TEX_ESC = [("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"), ("#", r"\#"), ("_", r"\_"),
            ("‖", r"$\Vert$"), ("→", r"$\rightarrow$"), ("←", r"$\leftarrow$"), ("×", r"$\times$"),
            ("≥", r"$\geq$"), ("≤", r"$\leq$"), ("≈", r"$\approx$"), ("·", r"$\cdot$"),
            ("–", "--"), ("①", "(1)"), ("②", "(2)"), ("③", "(3)"), ("⑤", "(5)"), ("④", "(4)")]


def tex(s: str) -> str:
    for a, b in _TEX_ESC:
        s = s.replace(a, b)
    return s.replace("\n", r"\\ ")


class Diagram:
    def __init__(self, name: str, w: float, h: float):
        self.name, self.w, self.h = name, w, h
        self.ops: list[tuple] = []
        style.apply()
        plt.rcParams["axes.grid"] = False
        self.fig = plt.figure(figsize=(w, h))
        self.ax = self.fig.add_axes([0, 0, 1, 1])
        self.ax.set_xlim(0, w)
        self.ax.set_ylim(0, h)
        self.ax.axis("off")
        self._checks: list[tuple] = []

    def box(self, x, y, w, h, text="", ls="-", fill="w", fs=7.0, bold=False, lw=0.7, ha="center", italic=False):
        """x,y = lower-left corner."""
        p = FancyBboxPatch((x, y), w, h, boxstyle="round,pad=0,rounding_size=0.04",
                           fc=FILLS[fill], ec="k", lw=lw, ls=ls, zorder=2)
        self.ax.add_patch(p)
        if text:
            tx = x + w / 2 if ha == "center" else x + 0.05
            t = self.ax.text(tx, y + h / 2, text, ha=ha, va="center", fontsize=fs, multialignment=ha,
                             fontweight="bold" if bold else "normal", style="italic" if italic else "normal",
                             zorder=4, linespacing=1.12)
            self._checks.append((t, x, y, w, h, text))
        self.ops.append(("box", x, y, w, h, text, ls, fill, fs, bold, lw, ha, italic))

    def text(self, x, y, text, fs=7.0, ha="center", va="center", bold=False, italic=False, bg=False):
        self.ax.text(x, y, text, ha=ha, va=va, fontsize=fs, multialignment=ha,
                     fontweight="bold" if bold else "normal", style="italic" if italic else "normal",
                     zorder=5, linespacing=1.12, bbox=dict(fc="white", ec="none", pad=0.6) if bg else None)
        self.ops.append(("text", x, y, text, fs, ha, va, bold, italic, bg))

    def arrow(self, pts, ls="-", lw=0.8, both=False):
        xs, ys = zip(*pts)
        if len(pts) > 2:
            self.ax.plot(xs[:-1], ys[:-1], color="k", lw=lw, ls=ls, zorder=1, solid_capstyle="butt")
        a = "<|-|>" if both else "-|>"
        self.ax.annotate("", xy=pts[-1], xytext=pts[-2], zorder=3,
                         arrowprops=dict(arrowstyle=a + ",head_length=0.28,head_width=0.14", color="k", lw=lw,
                                         ls=ls, shrinkA=0, shrinkB=0))
        self.ops.append(("arrow", list(pts), ls, lw, both))

    def line(self, pts, ls="-", lw=0.7):
        xs, ys = zip(*pts)
        self.ax.plot(xs, ys, color="k", lw=lw, ls=ls, zorder=1)
        self.ops.append(("line", list(pts), ls, lw))

    def check_fit(self):
        self.fig.canvas.draw()
        r = self.fig.canvas.get_renderer()
        inv = self.ax.transData.inverted()
        bad = []
        for t, x, y, w, h, text in self._checks:
            bb = t.get_window_extent(r)
            (x0, y0), (x1, y1) = inv.transform((bb.x0, bb.y0)), inv.transform((bb.x1, bb.y1))
            if x0 < x - 0.005 or x1 > x + w + 0.005 or y0 < y - 0.005 or y1 > y + h + 0.005:
                bad.append((text.replace("\n", " | ")[:40], round(x0 - x, 3), round(x + w - x1, 3),
                            round(y0 - y, 3), round(y + h - y1, 3)))
        return bad

    def tikz(self) -> str:
        L = ["% " + self.name + ": TikZ twin of paper/figures/" + self.name + ".pdf (generated by diag_common.py).",
             "% Coordinates are inches (y up). Needs \\usepackage{tikz}. Body font 7 pt.",
             "\\definecolor{dgA}{HTML}{F0F0F0}\\definecolor{dgB}{HTML}{DCDCDC}\\definecolor{dgC}{HTML}{C4C4C4}",
             "\\definecolor{dgAtk}{HTML}{F2C9B8}\\definecolor{dgHw}{HTML}{E3EEF7}",
             "\\begin{tikzpicture}[x=1in,y=1in,>=stealth,font=\\fontsize{7}{8}\\selectfont,line width=0.7pt]"]
        fillmap = {"w": "white", "g1": "dgA", "g2": "dgB", "g3": "dgC", "atk": "dgAtk", "hw": "dgHw"}
        dash = {"-": "", "--": "dashed", ":": "dotted", "-.": "dash dot"}
        for op in self.ops:
            k = op[0]
            if k == "box":
                _, x, y, w, h, text, ls, fill, fs, bold, lw, ha, italic = op
                opts = ["rounded corners=2.9pt", f"fill={fillmap[fill]}", f"line width={lw}pt"]
                if dash[ls]:
                    opts.append(dash[ls])
                L.append(f"\\draw[{','.join(opts)}] ({x:.3f},{y:.3f}) rectangle ({x+w:.3f},{y+h:.3f});")
                if text:
                    f = ("\\bfseries " if bold else "") + ("\\itshape " if italic else "") + \
                        f"\\fontsize{{{fs}}}{{{fs*1.12:.1f}}}\\selectfont "
                    al = "center" if ha == "center" else "flush left"
                    pos = f"({x+w/2:.3f},{y+h/2:.3f})" if ha == "center" else f"({x+0.05:.3f},{y+h/2:.3f})"
                    anc = "" if ha == "center" else ",anchor=west"
                    L.append(f"\\node[align={al}{anc},inner sep=0pt] at {pos} {{{f}{tex(text)}}};")
            elif k == "text":
                _, x, y, text, fs, ha, va, bold, italic, bg = op
                anc = {"center": "", "left": "anchor=west,", "right": "anchor=east,"}[ha]
                al = {"center": "center", "left": "flush left", "right": "flush right"}[ha]
                f = ("\\bfseries " if bold else "") + ("\\itshape " if italic else "") + \
                    f"\\fontsize{{{fs}}}{{{fs*1.12:.1f}}}\\selectfont "
                bgs = ",fill=white,inner sep=1pt" if bg else ",inner sep=0pt"
                L.append(f"\\node[{anc}align={al}{bgs}] at ({x:.3f},{y:.3f}) {{{f}{tex(text)}}};")
            elif k == "arrow":
                _, pts, ls, lw, both = op
                o = ["<->" if both else "->", f"line width={lw}pt"] + ([dash[ls]] if dash[ls] else [])
                L.append(f"\\draw[{','.join(o)}] " + " -- ".join(f"({x:.3f},{y:.3f})" for x, y in pts) + ";")
            elif k == "line":
                _, pts, ls, lw = op
                o = [f"line width={lw}pt"] + ([dash[ls]] if dash[ls] else [])
                L.append(f"\\draw[{','.join(o)}] " + " -- ".join(f"({x:.3f},{y:.3f})" for x, y in pts) + ";")
        L.append("\\end{tikzpicture}")
        return "\n".join(L) + "\n"

    def save(self):
        bad = self.check_fit()
        for b in bad:
            print("  OVERFLOW", self.name, b)
        style.save(self.fig, self.name)
        DIAG_DIR.mkdir(parents=True, exist_ok=True)
        (DIAG_DIR / f"{self.name}.tex").write_text(self.tikz(), encoding="utf-8")
        print("saved", self.name, "overflow:", len(bad))
